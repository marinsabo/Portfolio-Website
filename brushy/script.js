// ---------- LIGHTBOX ----------
const shots = [...document.querySelectorAll('.shot')];
const lb = document.getElementById('lb');
const lbImg = document.getElementById('lb-img');
const lbCap = document.getElementById('lb-cap');
let lbIdx = 0;
let lastFocus = null;

function showShot(i) {
  lbIdx = (i + shots.length) % shots.length;
  const img = shots[lbIdx].querySelector('img');
  lbImg.src = img.src;
  lbImg.alt = img.alt;
  lbCap.textContent = shots[lbIdx].querySelector('figcaption').textContent;
}
function openLb(i) {
  lastFocus = document.activeElement;
  showShot(i);
  lb.hidden = false;
  document.body.style.overflow = 'hidden';
  document.getElementById('lb-close').focus();
}
function closeLb() {
  lb.hidden = true;
  document.body.style.overflow = '';
  if (lastFocus) lastFocus.focus();
}

shots.forEach((s, i) => s.querySelector('button').addEventListener('click', () => openLb(i)));
document.getElementById('lb-close').addEventListener('click', closeLb);
document.getElementById('lb-prev').addEventListener('click', () => showShot(lbIdx - 1));
document.getElementById('lb-next').addEventListener('click', () => showShot(lbIdx + 1));
lb.addEventListener('click', e => { if (e.target === lb) closeLb(); });
document.addEventListener('keydown', e => {
  if (lb.hidden) return;
  if (e.key === 'Escape') closeLb();
  if (e.key === 'ArrowLeft') showShot(lbIdx - 1);
  if (e.key === 'ArrowRight') showShot(lbIdx + 1);
});

