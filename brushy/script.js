const EN = {};
const i18nEls = document.querySelectorAll('[data-i18n]');
i18nEls.forEach(el => { EN[el.dataset.i18n] = el.innerHTML; });
document.querySelectorAll('[data-i18n-content]').forEach(el => { EN[el.dataset.i18nContent] = el.content; });
document.querySelectorAll('[data-i18n-href]').forEach(el => { EN[el.dataset.i18nHref] = el.getAttribute('href'); });

function setLang(lang) {
  const dict = lang === 'hr' ? HR : EN;
  const t = key => dict[key] ?? EN[key];
  document.documentElement.lang = lang;
  i18nEls.forEach(el => {
    if (el.tagName === 'TITLE') document.title = t(el.dataset.i18n).replace(/&amp;/g, '&');
    else el.innerHTML = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-content]').forEach(el => { el.content = t(el.dataset.i18nContent); });
  document.querySelectorAll('[data-i18n-href]').forEach(el => { el.setAttribute('href', t(el.dataset.i18nHref)); });
  document.querySelectorAll('.lang__btn').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  syncAlts();
  try { localStorage.setItem('brushy-lang', lang); } catch (e) { /* storage unavailable */ }
}

function initialLang() {
  const param = new URLSearchParams(location.search).get('lang');
  if (param === 'hr' || param === 'en') return param;
  try {
    const saved = localStorage.getItem('brushy-lang');
    if (saved === 'hr' || saved === 'en') return saved;
  } catch (e) { /* storage unavailable */ }
  return 'en';
}

document.querySelectorAll('.lang__btn').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));

// Screenshot alt text follows the (translated) captions / feature titles
function syncAlts() {
  document.querySelectorAll('.shot').forEach(s => {
    s.querySelector('img').alt = s.querySelector('figcaption').textContent;
  });
  const active = document.querySelector('.ftab[aria-selected="true"] strong');
  if (active) featImg.alt = active.textContent;
}

// ---------- NAV ----------
const nav = document.getElementById('nav');
const navLinks = document.getElementById('nav-links');
const navToggle = document.getElementById('nav-toggle');

window.addEventListener('scroll', () => nav.classList.toggle('scrolled', window.scrollY > 10), { passive: true });

navToggle.addEventListener('click', () => {
  const open = navToggle.getAttribute('aria-expanded') !== 'true';
  navToggle.setAttribute('aria-expanded', String(open));
  navLinks.classList.toggle('open', open);
});
navLinks.querySelectorAll('a').forEach(a => a.addEventListener('click', () => {
  navToggle.setAttribute('aria-expanded', 'false');
  navLinks.classList.remove('open');
}));

// Highlight the nav link of the section in view
const sectionObs = new IntersectionObserver(entries => {
  entries.forEach(e => {
    if (!e.isIntersecting) return;
    navLinks.querySelectorAll('a').forEach(a => a.classList.toggle('active', a.hash === '#' + e.target.id));
  });
}, { rootMargin: '-45% 0px -50% 0px' });
['research', 'solution', 'features', 'parents', 'screens'].forEach(id => sectionObs.observe(document.getElementById(id)));

// ---------- SCROLL REVEAL ----------
const revealObs = new IntersectionObserver(entries => {
  entries.forEach((e, i) => {
    if (!e.isIntersecting) return;
    setTimeout(() => e.target.classList.add('visible'), i * 80);
    revealObs.unobserve(e.target);
  });
}, { threshold: 0.15 });
document.querySelectorAll('.reveal').forEach(el => revealObs.observe(el));

// ---------- STAT COUNT-UP ----------
const countObs = new IntersectionObserver(entries => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    const el = entry.target;
    const target = Number(el.dataset.count);
    const suffix = el.querySelector('span');
    const start = performance.now();
    const tick = now => {
      const p = Math.min((now - start) / 1200, 1);
      el.firstChild.textContent = Math.round(target * (1 - Math.pow(1 - p, 3)));
      if (p < 1) requestAnimationFrame(tick);
    };
    if (suffix) requestAnimationFrame(tick);
    countObs.unobserve(el);
  });
}, { threshold: 0.6 });
if (!matchMedia('(prefers-reduced-motion: reduce)').matches) {
  document.querySelectorAll('[data-count]').forEach(n => countObs.observe(n));
}

// ---------- FEATURE EXPLORER ----------
const featImg = document.getElementById('feat-img');
const tabs = [...document.querySelectorAll('.ftab')];

function selectTab(tab) {
  tabs.forEach(t => t.setAttribute('aria-selected', String(t === tab)));
  if (featImg.getAttribute('src') !== tab.dataset.img) {
    featImg.classList.add('swap');
    setTimeout(() => {
      featImg.src = tab.dataset.img;
      featImg.classList.remove('swap');
    }, 200);
  }
  featImg.alt = tab.querySelector('strong').textContent;
}

tabs.forEach((tab, i) => {
  tab.tabIndex = i === 0 ? 0 : -1;
  tab.addEventListener('click', () => selectTab(tab));
  tab.addEventListener('keydown', e => {
    if (!['ArrowDown', 'ArrowUp', 'ArrowRight', 'ArrowLeft'].includes(e.key)) return;
    e.preventDefault();
    const dir = e.key === 'ArrowDown' || e.key === 'ArrowRight' ? 1 : -1;
    const next = tabs[(i + dir + tabs.length) % tabs.length];
    tabs.forEach(t => { t.tabIndex = t === next ? 0 : -1; });
    next.focus();
    selectTab(next);
  });
});
tabs.forEach(t => new Image().src = t.dataset.img); // preload

